import { readFileSync } from 'fs';
import { extractFromFileAsync, pagesToOutlineText, extractFromFile } from '../packages/core';
const SP = 'tests/';
let n = 0, f = 0; const ok = (c: any, m: string) => { n++; if (!c) { f++; console.log('FAIL', m); } };
(async () => {
  const good = readFileSync(SP + 'fx/syl.pdf');
  const ex = await extractFromFileAsync('pdf', good);
  console.log(ex.method, '|', ex.note, '|', ex.nodes.map((x) => `${x.kind}:${x.name}@${x.page}`).join('; '));
  ok(ex.method === 'pdf text', 'method');
  const kinds = ex.nodes.map((x) => x.kind);
  ok(kinds.filter((k) => k === 'unit').length === 2 && kinds.filter((k) => k === 'chapter').length === 2 && kinds.filter((k) => k === 'topic').length === 2, 'units/chapters/topics read');
  ok(kinds.filter((k) => k === 'learning_outcome').length === 2 && kinds.includes('assessment_objective'), 'LO and AO read');
  ok(ex.nodes.find((x) => /Real Numbers/.test(x.name))?.page === 1 && ex.nodes.find((x) => /Polynomials/.test(x.name))?.page === 2, 'page numbers come from the PDF page');
  ok(ex.nodes.find((x) => /Zeros of a polynomial/.test(x.name))?.page === 9, 'explicit [p.9] in the text wins');
  ok(ex.nodes.every((x) => x.confidence <= 0.7), 'lower confidence so review asks for a check');
  ok(!ex.nodes.some((x) => /general paragraph|CBSE Class X/.test(x.name)), 'unlabelled lines never become items');
  ok(ex.unrecognised >= 2, 'unlabelled lines counted');
  const scan = await extractFromFileAsync('pdf', readFileSync(SP + 'fx/scan.pdf'));
  ok(scan.nodes.length === 0 && /no readable text/.test(scan.note), 'scanned PDF: told plainly, nothing invented');
  const bad = await extractFromFileAsync('pdf', Buffer.from('%PDF-1.4 not really a pdf'));
  ok(bad.nodes.length === 0 && /could not be read/.test(bad.note), 'corrupt PDF: no crash, stored, told');
  const empty = await extractFromFileAsync('pdf', Buffer.alloc(0));
  ok(empty.nodes.length === 0, 'empty buffer safe');
  ok(pagesToOutlineText(['Unit 1: A', 'Chapter 1: B [p.4]']).split('\n').join('|') === 'Unit 1: A|Chapter 1: B [p.4]' ? false : true, 'page marks added to pages');
  ok(pagesToOutlineText(['x', 'Chapter 1: B']).includes('Chapter 1: B [p.2]'), 'page index is the PDF page');
  const csv = await extractFromFileAsync('csv', Buffer.from('unit,chapter,topic\nU,C,T\n'));
  ok(csv.nodes.length >= 1, 'other types still work through the same entry point');
  ok(extractFromFile('pdf', good).nodes.length === 0, 'sync entry never reads a PDF (async only)');
  console.log(`t83: ${n - f}/${n} passed`); process.exit(f ? 1 : 0);
})();
