import { validateUsername, validatePassword, validateOptionalEmail, placeholderEmail, isPlaceholderEmail, normaliseUsername } from '../packages/core/auth/identity';
let ok=0,bad=0; const t=(n:string,c:boolean)=>{c?ok++:(bad++,console.log('FAIL',n))};
t('good',validateUsername('rahul_10')===null);
t('upper normalised',normaliseUsername(' Rahul.K ')==='rahul.k' && validateUsername(' Rahul.K ')===null);
t('short',validateUsername('ab')==='username_length');
t('long',validateUsername('a'.repeat(21))==='username_length');
t('space',validateUsername('ra hul')==='username_chars');
t('at',validateUsername('ra@hul')==='username_chars');
t('lead dot',validateUsername('.rahul')==='username_chars');
t('double dot',validateUsername('ra..hul')==='username_chars');
t('reserved',validateUsername('Admin')==='username_reserved');
t('pw short',validatePassword('abc12','x')==='password_short');
t('pw common',validatePassword('password123','x')==='password_weak');
t('pw repeat',validatePassword('aaaaaaaa','x')==='password_weak');
t('pw same',validatePassword('Rahul_10x','rahul_10x')==='password_same_as_username');
t('pw ok',validatePassword('Tiger#2027','rahul')===null);
t('email empty',validateOptionalEmail('')===null && validateOptionalEmail(undefined)===null);
t('email ok',validateOptionalEmail('a@b.in')===null);
t('email bad',validateOptionalEmail('a@b')==='invalid_email');
t('placeholder',placeholderEmail('Rahul')==='rahul@users.sahayak.invalid' && isPlaceholderEmail('rahul@users.sahayak.invalid') && !isPlaceholderEmail('a@gmail.com'));
console.log(ok,'ok',bad,'bad');
