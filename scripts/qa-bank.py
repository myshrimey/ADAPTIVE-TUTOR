#!/usr/bin/env python3
# Question-bank audit (v43). Machine checks only: structure, answer keys, duplicates, syllabus exclusions,
# numeric answers. It CANNOT judge whether a question is academically correct — a teacher must do that.
# Run: python3 scripts/qa-bank.py   (writes docs/QUESTION_BANK_AUDIT.md)
import json, glob, os, re, collections
SEED = os.path.join(os.path.dirname(__file__), '..', 'packages', 'db', 'seed')
EXCL = ['stri-shiksha','kanyadaan','george-pancham','bihari','madhur-madhur','girgit']
rows = []; report = []
tot = collections.Counter(); bad = collections.defaultdict(list)
for f in sorted(glob.glob(os.path.join(SEED, 'cbse-class10-*-diagnostic.json'))):
    name = os.path.basename(f).replace('cbse-class10-', '').replace('-diagnostic.json', '')
    cur = json.load(open(f.replace('-diagnostic', ''), encoding='utf-8'))
    skills = {s['slug'] for c in cur['chapters'] for t in c['topics'] for s in t['skills']}
    qs = json.load(open(f, encoding='utf-8'))['questions']
    seen = {}
    for i, q in enumerate(qs):
        tot[name] += 1
        def b(msg): bad[name].append(f'#{i} [{q.get("skill_slug")}] {msg}')
        if q['skill_slug'] not in skills: b('skill not in curriculum file')
        p = (q.get('prompt') or '').strip()
        if len(p) < 8: b('prompt too short')
        key = re.sub(r'\s+', ' ', p.lower())
        if key in seen: b(f'duplicate prompt of #{seen[key]}')
        seen[key] = i
        ea = q.get('expected_answer')
        val = ea.get('value') if isinstance(ea, dict) else ea
        if val in (None, ''): b('empty expected answer')
        t = q.get('question_type'); opts = q.get('options')
        if t == 'mcq':
            if not opts or len(opts) < 2: b('mcq without options')
            else:
                if len(set(map(str, opts))) != len(opts): b('duplicate options')
                if str(val) not in map(str, opts): b('answer not among options')
        if t == 'numeric':
            try: float(str(val).replace(',', ''))
            except Exception: b(f'numeric answer not a number: {val!r}')
        if q.get('difficulty') not in (1, 2, 3, 4, 5): b(f'difficulty {q.get("difficulty")}')
        if not q.get('misconception_tags'): b('no misconception tag')
        if any(x in (q['skill_slug'] + p).lower() for x in EXCL): b('mentions syllabus-excluded lesson')
        if q.get('explanation') is None and name in ('hindi', 'hindi-b'): b('no explanation')
    # skills never tested
    untested = skills - {q['skill_slug'] for q in qs}
    if untested: bad[name].append(f'{len(untested)} skills have no question: ' + ', '.join(sorted(untested)[:8]) + ('…' if len(untested) > 8 else ''))
    # answer-key position spread for MCQs
    pos = collections.Counter()
    for q in qs:
        if q.get('question_type') == 'mcq' and q.get('options'):
            v = str(q['expected_answer']['value'] if isinstance(q['expected_answer'], dict) else q['expected_answer'])
            o = list(map(str, q['options']))
            if v in o: pos[o.index(v)] += 1
    n = sum(pos.values())
    if n >= 20 and max(pos.values()) / n > 0.5: bad[name].append(f'answer key sits in one position {max(pos.values())}/{n} times (guessable)')
out = ['# Question bank audit (machine checks)', '', 'Generated by `python3 scripts/qa-bank.py`. This checks structure and obvious defects only. It does **not** prove an answer is academically correct; a teacher must still review every question.', '']
for n in sorted(tot):
    out.append(f'## {n}: {tot[n]} questions, {len(bad[n])} problems')
    for m in bad[n][:60]: out.append(f'- {m}')
    if len(bad[n]) > 60: out.append(f'- … and {len(bad[n]) - 60} more')
    out.append('')
open(os.path.join(os.path.dirname(__file__), '..', 'docs', 'QUESTION_BANK_AUDIT.md'), 'w', encoding='utf-8').write('\n'.join(out))
print('\n'.join(out[4:]))
